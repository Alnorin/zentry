#!/usr/bin/env node
// Compiles brain/**/*.md into brain/brain-data.js for brain.html.
// No dependencies. Run: node tools/build-brain.mjs
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, relative, basename, dirname, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'brain');

const walk = d => readdirSync(d).flatMap(f => {
  const p = join(d, f);
  return statSync(p).isDirectory() ? walk(p) : f.endsWith('.md') ? [p] : [];
});

function frontMatter(src) {
  const m = src.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!m) return [{}, src];
  const meta = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^([\w-]+):\s*(.*?)\s*(#.*)?$/);
    if (!kv) continue;
    let v = kv[2];
    if (/^\[.*\]$/.test(v)) v = v.slice(1, -1).split(',').map(s => s.trim().replace(/^["']|["']$/g, '')).filter(Boolean);
    else v = v.replace(/^["']|["']$/g, '');
    meta[kv[1]] = v;
  }
  return [meta, src.slice(m[0].length)];
}

const toTs = s => { const t = Date.parse(s); return isNaN(t) ? null : t; };
const pages = [];
for (const file of walk(dir).sort()) {
  const rel = relative(dir, file).split(sep).join('/');
  const raw = readFileSync(file, 'utf8');
  const [meta, body] = frontMatter(raw);
  const slug = basename(file, '.md');
  const folder = rel.includes('/') ? rel.split('/')[0] : 'Inbox';
  const mtime = statSync(file).mtimeMs;
  const created = toTs(meta.created) ?? mtime;
  const updated = toTs(meta.updated) ?? created;

  // ideas = "## " sections; text before the first one is the intro
  const ideas = [];
  let cur = null, inCode = false;
  for (const line of body.split(/\r?\n/)) {
    if (/^```/.test(line)) inCode = !inCode;
    const h = !inCode && line.match(/^##\s+(.+)/);
    if (h) { cur = { title: h[1].trim(), text: '' }; ideas.push(cur); }
    else if (cur) cur.text += line + '\n';
  }
  if (!ideas.length) ideas.push({ title: meta.title || slug, text: body });
  ideas.forEach(i => i.text = i.text.trim());

  const links = [...new Set([...body.matchAll(/\[\[([^\]|#]+)(?:[|#][^\]]*)?\]\]/g)].map(m => m[1].trim()))];
  const tasks = [...body.matchAll(/^\s*[-*]\s+\[( |x|X)\]\s+(.+)$/gm)].map(m => {
    const d = m[2].match(/@(\d{4}-\d{2}-\d{2})/);
    return { done: m[1] !== ' ', text: m[2].replace(/@\d{4}-\d{2}-\d{2}/, '').replace(/\s*→.*$/, '').trim(), due: d ? toTs(d[1] + 'T18:00:00') : null };
  });

  pages.push({
    slug, path: 'brain/' + rel, title: meta.title || slug, group: meta.group || folder,
    tags: Array.isArray(meta.tags) ? meta.tags : meta.tags ? [meta.tags] : [],
    created, updated, ideas, links, tasks, body: body.trim()
  });
}

const slugs = new Set(pages.map(p => p.slug));
for (const p of pages) p.links = p.links.filter(l => slugs.has(l) && l !== p.slug);

const config = (() => { try { return JSON.parse(readFileSync(join(dir, 'config.json'), 'utf8')); } catch { return {}; } })();
const data = { builtAt: Date.now(), config, pages };
writeFileSync(join(dir, 'brain-data.js'), '/* generated by tools/build-brain.mjs – do not edit */\nwindow.BRAIN = ' + JSON.stringify(data) + ';\n');
const ideas = pages.reduce((s, p) => s + p.ideas.length, 0), links = pages.reduce((s, p) => s + p.links.length, 0);
console.log(`brain: ${pages.length} pages, ${ideas} ideas, ${links} links`);
